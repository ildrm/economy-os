export function workbenchCopy(locale: Locale): CoreCopy {
  return copy[locale];
}

export function workbenchContextField(locale: Locale, field: ContextIssue): string {
  const messages = copy[locale];
  switch (field) {
    case "workspaceId":
      return messages.workspaceUuid;
    case "snapshotId":
      return messages.snapshotUuid;
    case "knownAt":
      return messages.asKnownAt;
    case "policy":
      return messages.policy;
    case "systemAt":
      return messages.systemTime;
  }
}

export function workbenchDimension(locale: Locale, dimension: VectorDimensionName): string {
  const messages = copy[locale];
  switch (dimension) {
    case "macroeconomic":
      return messages.macroeconomic;
    case "human_economic":
      return messages.humanEconomic;
    case "financial_system":
      return messages.financialSystem;
    case "market":
      return messages.market;
    case "regime":
      return messages.regime;
  }
}
